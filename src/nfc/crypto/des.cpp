  static inline uint64_t load64_be(const uint8_t b[DES_BLOCK_SIZE]) {
    return ((uint64_t)b[0] << 56) | ((uint64_t)b[1] << 48) |
          ((uint64_t)b[2] << 40) | ((uint64_t)b[3] << 32) |
          ((uint64_t)b[4] << 24) | ((uint64_t)b[5] << 16) |
          ((uint64_t)b[6] <<  8) | ((uint64_t)b[7] <<  0);
  }

  static inline void store64_be(uint64_t v, uint8_t b[DES_BLOCK_SIZE]) {
    b[0] = (uint8_t)(v >> 56); b[1] = (uint8_t)(v >> 48);
    b[2] = (uint8_t)(v >> 40); b[3] = (uint8_t)(v >> 32);
    b[4] = (uint8_t)(v >> 24); b[5] = (uint8_t)(v >> 16);
    b[6] = (uint8_t)(v >>  8); b[7] = (uint8_t)(v >>  0);
  }

  static inline uint32_t rotl28(uint32_t x, uint8_t s) {
    return ((x << s) | (x >> (28 - s))) & U28_MASK;
  }

  static inline uint64_t permute64(uint64_t in, const uint8_t *tbl, int nbits, int inbits) {
    uint64_t out = 0;
    for (int i = 0; i < nbits; i++) {
      out <<= 1;
      out |= (in >> (inbits - tbl[i])) & LB64_MASK;
    }
    return out;
  }

  static inline uint64_t des_ip(uint64_t in) { return permute64(in, IP, 64, 64); }
  static inline uint64_t des_pi(uint64_t in) { return permute64(in, PI, 64, 64); }

  static inline uint64_t des_expand32to48(uint32_t r) {
    uint64_t out = 0;
    for (int i = 0; i < 48; i++) {
      out <<= 1;
      out |= (uint64_t)((r >> (32 - E[i])) & LB32_MASK);
    }
    return out;
  }

  static inline uint32_t des_f(uint32_t r, uint64_t k48) {
    uint64_t x = des_expand32to48(r) ^ k48;
    uint32_t s_out = 0;

    for (int j = 0; j < DES_BLOCK_SIZE; j++) {
      uint8_t six = (uint8_t)((x >> (42 - 6 * j)) & 0x3fu);
      uint8_t row = (uint8_t)(((six & 0x20u) >> 4) | (six & 0x01u));
      uint8_t col = (uint8_t)((six >> 1) & 0x0fu);
      s_out = (s_out << 4) | (uint32_t)(S[j][(row << 4) | col] & 0x0fu);
    }

    uint32_t f = 0;
    for (int i = 0; i < 32; i++) {
      f <<= 1;
      f |= (s_out >> (32 - P[i])) & LB32_MASK;
    }
    return f;
  }

  void des_set_key_block64(des_ctx_t *ctx, uint64_t key64) {
    uint64_t pc1 = permute64(key64, PC1, 56, 64);
    uint32_t C = (uint32_t)((pc1 >> 28) & U28_MASK);
    uint32_t D = (uint32_t)(pc1 & U28_MASK);

    for (int round = 0; round < 16; round++) {
      C = rotl28(C, ITER_SHIFT[round]);
      D = rotl28(D, ITER_SHIFT[round]);
      uint64_t cd = (((uint64_t)C) << 28) | (uint64_t)D;
      ctx->subkey[round] = permute64(cd, PC2, 48, 56);
    }
  }
  void des_set_key(des_ctx_t *ctx, const uint8_t key[DES_BLOCK_SIZE]) {
    uint64_t v = load64_be(key);
    des_set_key_block64(ctx, v);
  }

  uint64_t des_encrypt_block64(const des_ctx_t *ctx, uint64_t in64) {
    uint64_t ip = des_ip(in64);
    uint32_t L = (uint32_t)(ip >> 32);
    uint32_t R = (uint32_t)ip;

    for (int i = 0; i < 16; i++) {
      uint32_t t = R;
      R = L ^ des_f(R, ctx->subkey[i]);
      L = t;
    }

    uint64_t pre = (((uint64_t)R) << 32) | (uint64_t)L;
    return des_pi(pre);
  }

  uint64_t des_decrypt_block64(const des_ctx_t *ctx, uint64_t in64) {
    uint64_t ip = des_ip(in64);
    uint32_t L = (uint32_t)(ip >> 32);
    uint32_t R = (uint32_t)ip;

    for (int i = 0; i < 16; i++) {
      uint32_t t = R;
      R = L ^ des_f(R, ctx->subkey[15 - i]);
      L = t;
    }

    uint64_t pre = (((uint64_t)R) << 32) | (uint64_t)L;
    return des_pi(pre);
  }

  void des_encrypt(const des_ctx_t *ctx, const uint8_t in[DES_BLOCK_SIZE], uint8_t out[DES_BLOCK_SIZE]) {
    uint64_t v = load64_be(in);
    v = des_encrypt_block64(ctx, v);
    store64_be(v, out);
  }

  void des_decrypt(const des_ctx_t *ctx, const uint8_t in[DES_BLOCK_SIZE], uint8_t out[DES_BLOCK_SIZE]) {
    uint64_t v = load64_be(in);
    v = des_decrypt_block64(ctx, v);
    store64_be(v, out);
  }

  /* IV behavior: if iv == NULL => all-zero IV */
  void des_cbc_encrypt(const des_ctx_t *ctx,
                      const uint8_t *in, uint8_t *out, size_t len,
                      const uint8_t iv[DES_BLOCK_SIZE]) {
    uint8_t prev[DES_BLOCK_SIZE] = {0};
    if (iv) {
      memcpy(prev, iv, DES_BLOCK_SIZE);
    }

    for (size_t off = 0; off < len; off += DES_BLOCK_SIZE) {
        uint8_t blk[DES_BLOCK_SIZE];
        for (int i = 0; i < DES_BLOCK_SIZE; i++) {
          blk[i] = in[off + i] ^ prev[i];
        }
        des_encrypt(ctx, blk, out + off);
        memcpy(prev, out + off, DES_BLOCK_SIZE);
    }
  }

  void des_cbc_decrypt(const des_ctx_t *ctx,
                    const uint8_t *in, uint8_t *out, size_t len,
                    const uint8_t iv[DES_BLOCK_SIZE]) {
    uint8_t prev[DES_BLOCK_SIZE] = {0};
    if (iv) {
      memcpy(prev, iv, DES_BLOCK_SIZE);
    }

    for (size_t off = 0; off < len; off += DES_BLOCK_SIZE) {
      uint8_t dec[DES_BLOCK_SIZE];
      des_decrypt(ctx, in + off, dec);
      for (int i = 0; i < DES_BLOCK_SIZE; i++) {
        out[off + i] = dec[i] ^ prev[i];
      }
      memcpy(prev, in + off, DES_BLOCK_SIZE);
    }
  }

  uint64_t tdes_encrypt_block64(const des_ctx_t *key1,
                                const des_ctx_t *key2,
                                const des_ctx_t *key3,
                                uint64_t in64) {
    uint64_t x = des_encrypt_block64(key1, in64);
    x = des_decrypt_block64(key2, x);
    x = des_encrypt_block64(key3, x);
    return x;
  }

  uint64_t tdes_decrypt_block64(const des_ctx_t *key1,
                                const des_ctx_t *key2,
                                const des_ctx_t *key3,
                                uint64_t in64) {
      uint64_t x = des_decrypt_block64(key1, in64);
      x = des_encrypt_block64(key2, x);
      x = des_decrypt_block64(key3, x);
      return x;
  }

  void tdes_encrypt_block(const des_ctx_t *key1,
                          const des_ctx_t *key2,
                          const des_ctx_t *key3,
                          const uint8_t in[DES_BLOCK_SIZE], uint8_t out[DES_BLOCK_SIZE]) {
    uint64_t v = load64_be(in);
    v = tdes_encrypt_block64(key1, key2, key3, v);
    store64_be(v, out);
  }
  void tdes_decrypt_block(const des_ctx_t *key1,
                          const des_ctx_t *key2,
                          const des_ctx_t *key3,
                          const uint8_t in[DES_BLOCK_SIZE], uint8_t out[DES_BLOCK_SIZE]) {
    uint64_t v = load64_be(in);
    v = tdes_decrypt_block64(key1, key2, key3, v);
    store64_be(v, out);
  }

